/**
 * Every file the route table is rendered into, keyed by its path from the
 * repository root, formatted the way `lint-staged` will leave it.
 *
 * Formatting here rather than trusting the emitter is what keeps
 * `generate --check` and `@r10c/docs-check` green after a commit: Prettier runs
 * on every staged `.yaml`, and a file it rewrites would otherwise never match
 * its generator again.
 */
import { join } from 'node:path';

import prettier from 'prettier';

import { envoyConfig } from './envoy.js';
import { gatewayManifests } from './gateway.js';
import { HEARTBEAT_S, IDLE_TIMEOUT_S } from './routes.js';
import { toYaml, toYamlStream } from './yaml.js';

const HEADER = [
  '# Generated by tools/edge from src/routes.ts — do not edit.',
  '# Regenerate with `pnpm nx run @r10c/edge:generate`.',
  `# Idle timeouts are ${String(IDLE_TIMEOUT_S)}s: over twice the ${String(HEARTBEAT_S)}s push heartbeat.`,
  '',
].join('\n');

/** Where the local config lands; `serve.sh` mounts it into the container. */
export const ENVOY_FILE = 'tools/edge/envoy.yaml';
export const GATEWAY_DIR = 'infra/cluster/edge';

const unformatted = (): Readonly<Record<string, string>> => ({
  [ENVOY_FILE]: HEADER + toYaml(envoyConfig()),
  ...Object.fromEntries(
    Object.entries(gatewayManifests()).map(([file, documents]) => [
      `${GATEWAY_DIR}/${file}`,
      HEADER + toYamlStream(documents),
    ]),
  ),
});

/** Path from the repository root → the file's exact contents. */
export const renderEdge = async (
  repoRoot: string,
): Promise<Readonly<Record<string, string>>> => {
  const entries = await Promise.all(
    Object.entries(unformatted()).map(async ([path, text]) => {
      const filepath = join(repoRoot, path);
      const options = await prettier.resolveConfig(filepath);
      return [path, await prettier.format(text, { ...options, filepath })];
    }),
  );
  return Object.fromEntries(entries) as Record<string, string>;
};
