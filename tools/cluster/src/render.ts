/**
 * Every file the fleet is rendered into, keyed by its path from the repository
 * root, formatted the way `lint-staged` will leave it — the edge's pattern
 * (`tools/edge/src/render.ts`), for the same reason: Prettier runs on every
 * staged `.yaml`, and a file it rewrites would otherwise never match its
 * generator again.
 *
 * The emitter is `tools/edge`'s, handed in with the inputs for the reason
 * `fleet.ts` gives: one YAML writer in the repository, not two.
 */
import { join } from 'node:path';

import prettier from 'prettier';

import {
  type FleetInputs,
  fleetKustomization,
  fleetManifests,
  type Yaml,
} from './fleet.js';

/** `toYaml` and `toYamlStream` from `tools/edge`. */
export interface YamlEmitter {
  readonly toYaml: (value: Yaml) => string;
  readonly toYamlStream: (documents: readonly Yaml[]) => string;
}

const HEADER = [
  '# Generated by tools/cluster from FLEET (tools/slices) and ORIGINS (tools/edge) — do not edit.',
  '# Regenerate with `pnpm nx run @r10c/cluster:generate`.',
  '',
].join('\n');

export const FLEET_DIR = 'infra/cluster/fleet';

const unformatted = (
  inputs: FleetInputs,
  { toYaml, toYamlStream }: YamlEmitter,
): Readonly<Record<string, string>> => ({
  [`${FLEET_DIR}/kustomization.yaml`]:
    HEADER + toYaml(fleetKustomization(inputs)),
  ...Object.fromEntries(
    Object.entries(fleetManifests(inputs)).map(([file, documents]) => [
      `${FLEET_DIR}/${file}`,
      HEADER + toYamlStream(documents),
    ]),
  ),
});

/** Path from the repository root → the file's exact contents. */
export const renderCluster = async (
  repoRoot: string,
  inputs: FleetInputs,
  emitter: YamlEmitter,
): Promise<Readonly<Record<string, string>>> => {
  const entries = await Promise.all(
    Object.entries(unformatted(inputs, emitter)).map(async ([path, text]) => {
      const filepath = join(repoRoot, path);
      const options = await prettier.resolveConfig(filepath);
      return [path, await prettier.format(text, { ...options, filepath })];
    }),
  );
  return Object.fromEntries(entries) as Record<string, string>;
};
